// 🔴 Nível 6 — Combinando métodos
// 21. Organizando uma lista

const nomes = [
    'Emanuelly',
    'Letícia',
    'Maria Eduarda',
    'Gabriela',
    'Pamela',
    'Paloma',
    'Anabelle',
    'Kevin',
];

// 1. original
console.log(nomes);

// 2. sort()
nomes.sort();
console.log(nomes);

// 3. reverse()
nomes.reverse();
console.log(nomes);

// 4. join()
console.log(nomes.join(' '));
